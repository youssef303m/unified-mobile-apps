// Generates src/config.ts from iboplayer-mobile-kit/02-backend/config.json (AGENTS.md rule 7).
// Run: npm run config:generate. Never edit src/config.ts by hand.
//
// Left out on purpose (02-backend/config.md): `tvBootOnly` and `store` (TV boot loader only),
// `stararcs.tvAssetToken` (TV boot loader only) and `defaults.tvFallbackMac` (the shared TV
// MAC the phone must never use).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "iboplayer-mobile-kit", "02-backend", "config.json");
const target = join(root, "src", "config.ts");

const config = JSON.parse(readFileSync(source, "utf8"));
delete config.tvBootOnly;
delete config.store;
delete config.stararcs.tvAssetToken;
delete config.defaults.tvFallbackMac;

const banner = [
  "// GENERATED by scripts/generate-config.mjs from iboplayer-mobile-kit/02-backend/config.json.",
  "// Do not edit. App-level keys the TV apps already ship (02-backend/config.md): treat as public,",
  "// but never log stream URLs or credentials built from them.",
  "",
].join("\n");

writeFileSync(
  target,
  `${banner}export const config = ${JSON.stringify(config, null, 2)} as const;\n`,
);
console.log(`Wrote ${target}`);
